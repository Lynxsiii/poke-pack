// The table of every finish the site draws: one row per finish signature (era, family, pattern classes, reverse or
// not), with how many card faces use it, two example ids and the stylesheet that paints it.
//
//   node .claude/skills/card-textures/scripts/finish_table.mjs            # writes reference/finishes.json and .md
//   node .claude/skills/card-textures/scripts/finish_table.mjs --check    # exit 1 if a finish has no family
//
// Built from foil_census.mjs (the site's own classifier and family registry), so it can never list a finish the site
// does not draw. A row with no family is painted only by the shared era sheets: those are the finishes the
// 2026-11-25 visibility sweep found hardest to keep visible, and the ones a new set is most likely to land on by
// accident. Step 2 of the general holo system (thread "Get the holos working", 2026-11-25): first see every finish in
// one place, then fold the recipes into it.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..", "..");
const REF = join(HERE, "..", "reference");
const faces = JSON.parse(execFileSync("node", [join(HERE, "foil_census.mjs")], { cwd: ROOT, maxBuffer: 1 << 28 }).toString());

const strip = (cls) => cls.split(/\s+/).filter((c) => c && !/^(cure-|has-stamp)/.test(c)).sort().join(" ");
const rows = new Map();
for (const f of faces) {
  const key = [f.era, f.family, f.pattern, strip(f.classes), f.reverse ? "reverse" : "plain"].join("|");
  let r = rows.get(key);
  if (!r) {
    r = { era: f.era, family: f.family, pattern: f.pattern, classes: strip(f.classes), reverse: f.reverse, faces: 0,
      rarities: new Set(), sets: new Set(), examples: [] };
    rows.set(key, r);
  }
  r.faces += 1;
  r.rarities.add(f.rarity);
  r.sets.add(f.set);
  if (r.examples.length < 2) r.examples.push(`${f.id}${f.reverse ? " (reverse)" : ""}`);
}

const sheet = (r) => (r.family && existsSync(join(ROOT, "css/holo/fam", `${r.family}.css`)) ? `css/holo/fam/${r.family}.css` : "");
const ERA_ORDER = ["me", "sv", "swsh", "sm", "xy", "bw", "dp", "ex", "wotc", "other"];
const table = [...rows.values()]
  .map((r) => ({ ...r, rarities: [...r.rarities].sort(), sets: r.sets.size, sheet: sheet(r) }))
  .sort((a, b) => ERA_ORDER.indexOf(a.era) - ERA_ORDER.indexOf(b.era) || (a.family || "~").localeCompare(b.family || "~") ||
    b.faces - a.faces);

const orphans = table.filter((r) => !r.family);
if (process.argv.includes("--check")) {
  for (const r of orphans) console.log(`no family: ${r.era} ${r.pattern} [${r.classes}] ${r.faces} faces, e.g. ${r.examples[0]}`);
  console.error(`${table.length} finishes, ${orphans.length} with no family (${orphans.reduce((n, r) => n + r.faces, 0)} faces)`);
  process.exit(orphans.length ? 1 : 0);
}

writeFileSync(join(REF, "finishes.json"), `${JSON.stringify(table, null, 1)}\n`);
const md = [
  "# Every finish the site draws",
  "",
  `Generated by \`scripts/finish_table.mjs\` from the site's own classifier: ${table.length} finish signatures over ` +
    `${faces.length.toLocaleString("en-US")} card faces. Do not edit by hand; run the script after changing a family or the classifier.`,
  `${orphans.length} signatures (${orphans.reduce((n, r) => n + r.faces, 0).toLocaleString("en-US")} faces) have no family and are painted only by the shared era sheets.`,
  "",
  "| Era | Family | Pattern | Faces | Sets | Rarities | Example |",
  "|---|---|---|---:|---:|---|---|",
  ...table.map((r) => `| ${r.era} | ${r.family || "_none_"} | \`${r.pattern}\`${r.reverse ? " (reverse)" : ""} | ${r.faces} | ${r.sets} | ${r.rarities.slice(0, 3).join(", ")}${r.rarities.length > 3 ? ", ..." : ""} | ${r.examples[0]} |`),
  "",
].join("\n");
writeFileSync(join(REF, "finishes.md"), md);
console.log(`${table.length} finishes, ${orphans.length} with no family; wrote reference/finishes.json and reference/finishes.md`);
