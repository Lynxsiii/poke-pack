// Writes js/set-chase.js: one chase card image per playable set, for the mastery
// banners. The pick is deterministic: the first of the set's heroIds (the
// catalog's own "chase" list) that exists in the set's card data, else the
// set's highest-rarity card by the pull-odds order, then the lowest number.
// Only files already on the site are used. Re-run after adding a set:
//   node scripts/make_set_chase.mjs
import fs from "node:fs";
import { PLAYABLE_SETS, dataSetsOf } from "../js/catalog.js";

const read = (file) => JSON.parse(fs.readFileSync(new URL(`../${file}`, import.meta.url), "utf8"));
const here = (p) => fs.existsSync(new URL(`../${p}`, import.meta.url));
const RANK = ["hyper", "secret", "rainbow", "special illustration", "illustration rare", "ultra", "amazing", "holo", "rare", "promo"];
const rarityScore = (r) => {
  const i = RANK.findIndex((k) => String(r || "").toLowerCase().includes(k));
  return i < 0 ? 99 : i;
};

const out = {};
for (const set of PLAYABLE_SETS) {
  const cards = dataSetsOf(set).flatMap((s) => (s.dataFile ? Object.values(read(s.dataFile)) : []));
  const byId = new Map(cards.map((c) => [c.id, c]));
  let pick = (set.heroIds || []).map((id) => byId.get(id)).find((c) => c?.image && here(c.image));
  if (!pick) {
    pick = cards
      .filter((c) => c.image && here(c.image))
      .sort((a, b) => rarityScore(a.rarity) - rarityScore(b.rarity) || String(a.number).localeCompare(String(b.number), "en", { numeric: true }))[0];
  }
  if (!pick) {
    console.warn(`no chase card for ${set.id}`);
    continue;
  }
  out[set.id] = pick.image;
}

const rows = Object.entries(out).map(([id, image]) => `  ${JSON.stringify(id)}: ${JSON.stringify(image)},`).join("\n");
fs.writeFileSync(
  new URL("../js/set-chase.js", import.meta.url),
  `/* Generated by scripts/make_set_chase.mjs. Do not edit by hand. One chase card image per set
   (the catalog's first hero card), used as the art in the mastery banners. A set that is
   missing here still gets a banner: js/mastery-banner.js draws it without the card. */\nexport const SET_CHASE = {\n${rows}\n};\n`,
);
console.log(`${Object.keys(out).length} of ${PLAYABLE_SETS.length} sets`);
