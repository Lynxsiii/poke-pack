/* Regenerates worker/casino-ddl.js from worker/migrations/0015_casino_coinflip.sql
   (CASINO_DDL), 0016_casino_jackpot.sql (JACKPOT_DDL), 0017_casino_sales.sql (SALES_DDL)
   and 0022_casino_slabs.sql (SLABS_COLUMNS: its ALTER TABLE ADD COLUMNs, each as
   [table, column, sql]; SLABS_DDL: its trigger replacements, in file order).
   The Worker cannot read files, and nobody can run remote migrations, so it
   applies the same DDL to itself (worker/casino.js, worker/casino-slabs.js).
   Edit the .sql, run `node scripts/gen-casino-ddl.mjs`; scripts/test-coinflip.mjs,
   scripts/test-jackpot.mjs and scripts/test-casino-slabs.mjs fail if they drift. */
import { readFileSync, writeFileSync } from 'node:fs';

export function splitStatements(sql) {
  const out = []; let cur = []; let trigger = false;
  for (const raw of sql.split('\n')) {
    const line = raw.trimEnd();
    if (!cur.length && (!line.trim() || line.trim().startsWith('--'))) continue;
    if (!cur.length) trigger = /^CREATE TRIGGER/i.test(line.trim());
    cur.push(line);
    const done = trigger ? line.trim() === 'END;' : line.endsWith(';');
    if (done) { out.push(cur.join('\n').replace(/;$/, '')); cur = []; }
  }
  if (cur.length) throw new Error('unterminated statement: ' + cur[0]);
  return out;
}

/** 0022's statements as { columns: [[table, column, sql]], ddl: [sql] }: an ALTER is applied only when its column is missing. */
export function splitSlabs(sql) {
  const columns = []; const ddl = [];
  for (const statement of splitStatements(sql)) {
    const alter = statement.match(/^ALTER TABLE (\w+) ADD COLUMN (\w+)\b/);
    if (alter) columns.push([alter[1], alter[2], statement]); else ddl.push(statement);
  }
  return { columns, ddl };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = name => readFileSync(new URL(`../worker/migrations/${name}`, import.meta.url), 'utf8');
  const coinflip = splitStatements(text('0015_casino_coinflip.sql')); const jackpot = splitStatements(text('0016_casino_jackpot.sql'));
  const sales = splitStatements(text('0017_casino_sales.sql')); const slabs = splitSlabs(text('0022_casino_slabs.sql'));
  writeFileSync(new URL('../worker/casino-ddl.js', import.meta.url),
    `// Generated by scripts/gen-casino-ddl.mjs from worker/migrations/0015_casino_coinflip.sql, 0016_casino_jackpot.sql, 0017_casino_sales.sql and 0022_casino_slabs.sql. Do not edit.\n` +
    `export const CASINO_DDL = ${JSON.stringify(coinflip, null, 2)};\n` +
    `export const JACKPOT_DDL = ${JSON.stringify(jackpot, null, 2)};\n` +
    `export const SALES_DDL = ${JSON.stringify(sales, null, 2)};\n` +
    `export const SLABS_COLUMNS = ${JSON.stringify(slabs.columns, null, 2)};\n` +
    `export const SLABS_DDL = ${JSON.stringify(slabs.ddl, null, 2)};\n`);
  console.log(`${coinflip.length} coinflip + ${jackpot.length} jackpot + ${sales.length} sales + ${slabs.columns.length} slab columns + ${slabs.ddl.length} slab statements`);
}
