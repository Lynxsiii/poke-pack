/* Regenerates worker/casino-ddl.js from worker/migrations/0014_casino_coinflip.sql
   (CASINO_DDL), 0015_casino_jackpot.sql (JACKPOT_DDL) and 0016_casino_sales.sql (SALES_DDL).
   The Worker cannot read files, and nobody can run remote migrations, so it
   applies the same DDL to itself (worker/casino.js). Edit the .sql, run
   `node scripts/gen-casino-ddl.mjs`; scripts/test-coinflip.mjs and
   scripts/test-jackpot.mjs fail if they drift. */
import { readFileSync, writeFileSync } from 'node:fs';

export function splitStatements(sql) {
  const out = []; let cur = []; let trigger = false;
  for (const raw of sql.split('\n')) {
    const line = raw.trimEnd();
    if (!cur.length && (!line.trim() || line.trim().startsWith('--'))) continue;
    if (!cur.length) trigger = /^CREATE TRIGGER/i.test(line.trim());
    cur.push(line);
    const done = trigger ? line.trim() === 'END;' : line.endsWith(';');
    if (done) { out.push(cur.join('\n').replace(/;$/, '')); cur = []; }
  }
  if (cur.length) throw new Error('unterminated statement: ' + cur[0]);
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const read = name => splitStatements(readFileSync(new URL(`../worker/migrations/${name}`, import.meta.url), 'utf8'));
  const coinflip = read('0014_casino_coinflip.sql'); const jackpot = read('0015_casino_jackpot.sql'); const sales = read('0016_casino_sales.sql');
  writeFileSync(new URL('../worker/casino-ddl.js', import.meta.url),
    `// Generated by scripts/gen-casino-ddl.mjs from worker/migrations/0014_casino_coinflip.sql, 0015_casino_jackpot.sql and 0016_casino_sales.sql. Do not edit.\n` +
    `export const CASINO_DDL = ${JSON.stringify(coinflip, null, 2)};\n` +
    `export const JACKPOT_DDL = ${JSON.stringify(jackpot, null, 2)};\n` +
    `export const SALES_DDL = ${JSON.stringify(sales, null, 2)};\n`);
  console.log(`${coinflip.length} coinflip + ${jackpot.length} jackpot statements`);
}
