/* Regenerates worker/casino-ddl.js from worker/migrations/0014_casino_coinflip.sql.
   The Worker cannot read files, and nobody can run remote migrations, so it
   applies the same DDL to itself (worker/casino.js). Edit the .sql, run
   `node scripts/gen-casino-ddl.mjs`; scripts/test-coinflip.mjs fails if they drift. */
import { readFileSync, writeFileSync } from 'node:fs';

export function splitStatements(sql) {
  const out = []; let cur = []; let trigger = false;
  for (const raw of sql.split('\n')) {
    const line = raw.trimEnd();
    if (!cur.length && (!line.trim() || line.trim().startsWith('--'))) continue;
    if (!cur.length) trigger = /^CREATE TRIGGER/i.test(line.trim());
    cur.push(line);
    const done = trigger ? line.trim() === 'END;' : line.endsWith(';');
    if (done) { out.push(cur.join('\n').replace(/;$/, '')); cur = []; }
  }
  if (cur.length) throw new Error('unterminated statement: ' + cur[0]);
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const sql = readFileSync(new URL('../worker/migrations/0014_casino_coinflip.sql', import.meta.url), 'utf8');
  const statements = splitStatements(sql);
  writeFileSync(new URL('../worker/casino-ddl.js', import.meta.url),
    `// Generated by scripts/gen-casino-ddl.mjs from worker/migrations/0014_casino_coinflip.sql. Do not edit.\n` +
    `export const CASINO_DDL = ${JSON.stringify(statements, null, 2)};\n`);
  console.log(`${statements.length} statements`);
}
