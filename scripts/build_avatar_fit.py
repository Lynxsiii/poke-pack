#!/usr/bin/env python3
"""Build js/avatar-fit.js: where each sprite's Pokémon sits inside its picture.

    python3 scripts/build_avatar_fit.py --cache /tmp/avatar-cache

A pixel sprite is a 96px canvas with the Pokémon somewhere in the middle, and
an animated sprite's canvas is as big as its widest frame, so the body often
sits in a corner (a tail that sways to the right leaves the body on the left).
Drawn as they come, they land off-centre and small or cropped in a round face.

For every picture in js/avatar-dex.js this measures the body and writes the
move and zoom that centre it and make it fill the same share of the face:
    id: [pixel x, pixel y, pixel zoom, animated x, animated y, animated zoom]
x and y are percent of the face, zoom is in hundredths. js/cosmetics.js
(avatarFit) turns a row into the style on the <img>. Run after build_avatars.py.
"""
import argparse, json, re, subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parent.parent
SPRITES = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/"
FILL = 0.78       # share of the face's width the body's longer side takes
ZOOM = (0.7, 2.6)  # never shrink to a dot or blow a tiny sprite up to mush
REACH = 0.15      # ...or, for a Pokémon that moves bodily, in this share
STEADY = 0.55     # an animated pixel counts as body when it is drawn in this share of the frames


def fetch(job):
    url, out = job
    if not out.exists() or out.stat().st_size < 60:
        subprocess.run(["curl", "-s", "-f", "--retry", "3", "--retry-all-errors", "-o", str(out), url], capture_output=True)


def fit(box, size):
    """(x%, y%, zoom*100) that centres `box` of a `size` canvas drawn object-fit: contain in a square."""
    if not box:
        return [0, 0, 100]
    w, h = size
    side = max(w, h)
    bw, bh = box[2] - box[0], box[3] - box[1]
    zoom = min(ZOOM[1], max(ZOOM[0], FILL / (max(bw, bh) / side)))
    x = -((box[0] + box[2]) / 2 - w / 2) / side * 100
    y = -((box[1] + box[3]) / 2 - h / 2) / side * 100
    return [round(x), round(y), round(zoom * 100)]


def still_box(path):
    im = Image.open(path).convert("RGBA")
    return im.getchannel("A").point(lambda a: 255 if a > 40 else 0).getbbox(), im.size


def moving_box(path):
    im = Image.open(path)
    frames = getattr(im, "n_frames", 1)
    step = -(-frames // 30)
    used = len(range(0, frames, step))
    # At most 30 frames are sampled, so the per-pixel count fits an 8-bit image.
    total = Image.new("L", im.size, 0)
    for i in range(0, frames, step):
        im.seek(i)
        mask = im.convert("RGBA").getchannel("A").point(lambda a: 1 if a > 40 else 0)
        total = ImageChops.add(total, mask)
    def box(share):
        need = max(1, int(used * share))
        return total.point(lambda v: 255 if v >= need else 0).getbbox()

    # The body is what stays drawn most of the time; a swaying tail is left out. A Pokémon that flaps or bobs
    # has no such still part (the steady box is a sliver of it), so it is measured by everywhere it goes.
    steady, reach = box(STEADY), box(REACH)
    side = lambda b: max(b[2] - b[0], b[3] - b[1]) if b else 0
    return (steady if side(steady) >= 0.75 * side(reach) else reach), im.size

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=str(ROOT / ".avatar-cache"))
    args = ap.parse_args()
    cache = Path(args.cache)
    for sub in ("raw/pixel", "raw/anim"):
        (cache / sub).mkdir(parents=True, exist_ok=True)
    dex = (ROOT / "js" / "avatar-dex.js").read_text(encoding="utf8")
    rows = [(int(a), int(b)) for a, b in re.findall(r'\[(\d+),"[^"]*",(\d+)', dex)]
    jobs = []
    for pid, flags in rows:
        if flags & 4:
            jobs.append((SPRITES + f"{pid}.png", cache / "raw/pixel" / f"{pid}.png"))
        if flags & 16:
            jobs.append((SPRITES + f"other/showdown/{pid}.gif", cache / "raw/anim" / f"{pid}.gif"))
    for _ in range(3):
        with ThreadPoolExecutor(24) as pool:
            list(pool.map(fetch, jobs))
    out = {}
    missing = 0
    for pid, flags in rows:
        row = [0, 0, 100, 0, 0, 100]
        for at, bit, path, measure in ((0, 4, cache / "raw/pixel" / f"{pid}.png", still_box), (3, 16, cache / "raw/anim" / f"{pid}.gif", moving_box)):
            if not flags & bit:
                continue
            try:
                row[at:at + 3] = fit(*measure(path))
            except Exception:
                missing += 1
        out[pid] = row
    lines = [
        "// GENERATED by scripts/build_avatar_fit.py. Do not edit.",
        "// Where each sprite's Pokémon sits in its picture: id: [pixel x, y, zoom, animated x, y, zoom]. x and y are percent of the face, zoom is in hundredths.",
        "export const AVATAR_FIT = " + json.dumps(out, separators=(",", ":")).replace('"', "") + ";",
    ]
    (ROOT / "js" / "avatar-fit.js").write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"{len(out)} pictures, {missing} could not be measured")


if __name__ == "__main__":
    main()
