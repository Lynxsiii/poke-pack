"""Pick the sleeve and coin that mastering a set (or crowning an era) gifts.

Mastering a set hands out that set's OWN gear from data/gear.json: every sleeve
and coin there lists the sets it belongs to (`sets: [setId]`). For each playable
set this picks, deterministically:

  sleeve  the foil sleeves first (item has `foil`), then the id, A to Z
  coin    the coins that belong to that set alone first, then real photos over
          drawn art, then metal over plastic, then the id

A set with no sleeve or no coin gets just the other; a set with neither gets
nothing. An era crown (every set of the era mastered) gets one more sleeve and
coin out of the era's sets that no set mastery or level already gives away (foil first,
then the era's own set order), falling back to any of the era's gear when every
piece is already a set gift. The eras come from the same rule the achievement
table uses (CROWN_ERAS in js/achievement-eras.js), so a new era is picked up by
re-running this script.

    python3 scripts/make_mastery_gifts.py

Writes data/mastery-gifts.json and js/mastery-gifts.js (the Worker and the page
import the latter, the same way as js/set-accents.js). Re-run it after
data/gear.json or the set list changes; scripts/test-mastery.mjs fails when the
generated file is stale.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def catalog_sets() -> dict:
    js = (
        "Promise.all([import('./js/catalog.js'),import('./js/achievement-eras.js'),import('./js/levels.js')]).then(([c,e,l])=>"
        "console.log(JSON.stringify({level:Object.values(l.LEVEL_GEAR).flat(),sets:c.PLAYABLE_SETS.map(s=>({id:s.id,era:s.era||s.edition||''})),"
        "crowns:e.CROWN_ERAS.map(era=>({era,slug:e.eraSlug(era),sets:e.setsInEra(era).map(s=>s.id)}))})))"
    )
    out = subprocess.run(["node", "-e", js], cwd=ROOT, capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def entry(kind: str, item: dict) -> dict:
    return {"kind": kind, "id": item["id"], "name": item["name"]}


def sleeve_key(item: dict, rank: int = 0):
    return (0 if item.get("foil") else 1, rank, item["id"])


def coin_key(item: dict, rank: int = 0):
    return (
        len(item.get("sets", [])),
        1 if item.get("drawn") else 0,
        0 if item.get("material") == "metal" else 1,
        rank,
        item["id"],
    )


def main() -> None:
    gear = json.loads((ROOT / "data" / "gear.json").read_text())
    info = catalog_sets()
    order = [s["id"] for s in info["sets"]]

    def owned(kind: str, set_id: str) -> list[dict]:
        table = gear["sleeves" if kind == "sleeve" else "coins"]
        return [item for item in table.values() if set_id in item.get("sets", [])]

    # The level road (LEVEL_GEAR in js/levels.js) already gives some pieces away: a set mastery never
    # repeats one, it takes the set's next best piece or, if that was its only one of the kind, none.
    level_taken = {(g["kind"], g["id"]) for g in info["level"]}

    gifts: dict[str, list[dict]] = {}
    for set_id in order:
        picks = []
        sleeves = sorted((i for i in owned("sleeve", set_id) if ("sleeve", i["id"]) not in level_taken), key=sleeve_key)
        coins = sorted((i for i in owned("coin", set_id) if ("coin", i["id"]) not in level_taken), key=coin_key)
        if sleeves:
            picks.append(entry("sleeve", sleeves[0]))
        if coins:
            picks.append(entry("coin", coins[0]))
        gifts[set_id] = picks

    # The crowns skip every set gift and every level gift too.
    taken = {(g["kind"], g["id"]) for picks in gifts.values() for g in picks} | level_taken
    crowns: dict[str, list[dict]] = {}
    for crown in info["crowns"]:
        picks = []
        for kind, keyfn in (("sleeve", sleeve_key), ("coin", coin_key)):
            pool = []
            for rank, set_id in enumerate(crown["sets"]):
                pool.extend((keyfn(item, rank), item) for item in owned(kind, set_id))
            fresh = [row for row in pool if (kind, row[1]["id"]) not in taken]
            best = sorted(fresh or pool, key=lambda row: row[0])
            if best:
                picks.append(entry(kind, best[0][1]))
                taken.add((kind, best[0][1]["id"]))
        crowns[crown["slug"]] = picks

    payload = {"sets": gifts, "crowns": crowns}
    (ROOT / "data" / "mastery-gifts.json").write_text(json.dumps(payload, indent=1, ensure_ascii=False) + "\n")

    lines = [
        "/* Generated by scripts/make_mastery_gifts.py from data/gear.json. Do not edit by hand:",
        "   change the pick rules in the script and run it again. Inlined so the Worker can import it.",
        "   MASTERY_GIFTS: set id to the sleeve/coin its mastery gifts. CROWN_GIFTS: era slug to its crown gifts. */",
        "export const MASTERY_GIFTS = {",
    ]
    for set_id, picks in gifts.items():
        lines.append(f"  {json.dumps(set_id)}: {json.dumps(picks, ensure_ascii=False)},")
    lines += ["};", "", "export const CROWN_GIFTS = {"]
    for slug, picks in crowns.items():
        lines.append(f"  {json.dumps(slug)}: {json.dumps(picks, ensure_ascii=False)},")
    lines += ["};", ""]
    (ROOT / "js" / "mastery-gifts.js").write_text("\n".join(lines))

    with_both = sum(1 for p in gifts.values() if len(p) == 2)
    with_one = sum(1 for p in gifts.values() if len(p) == 1)
    none = [s for s, p in gifts.items() if not p]
    print(f"{len(gifts)} sets: {with_both} get a sleeve and a coin, {with_one} get one, {len(none)} get none {none}")
    for slug, picks in crowns.items():
        print(f"crown {slug}: {[p['id'] for p in picks]}")


if __name__ == "__main__":
    main()
