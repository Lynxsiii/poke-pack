/**
 * Holo family me-reverse: the Mega Evolution reverse holos (reverse round, 2026-11-28).
 *
 * Scope: every plain reverse face of me1-me6, me2pt5 and the 30th Celebration me55 (792 faces): the faces the era
 * marks `rev-mirror` (TCG Live's reverse maps are a plain mirror for the whole era, reference/sv-reverse.md), and me55,
 * which reverseFinish() leaves without a finish (it fell to the generic cosmos tile: white cracked blotches). Not
 * claimed: a face with a reverse map, a pattern or a reverse kind of its own.
 *
 * The era drew the mirror with sv-reverse.css's colour dodge: every pale text box blew to flat white with no falloff,
 * a coloured one took an even orange-to-lemon wash (2026-11-28 reverse review: 20 of 21 bad).
 *
 * What it adds (css/holo/fam/me-reverse.css, generated by scripts/fam/mirror-reverse/make_sheets.py):
 *   fam-me-reverse   every face it claims. The mask is the card less the layout's art window (the site's --win-*).
 *
 * `base` is foilExtras()'s own result for the face. Never import js/foil-maps.js from here (it waits on this module).
 */
const SET = /^me(\d+(pt5)?|55)-/;

/** Whether a card face is this family's. */
export function claims(card, base) {
  if (!card?.reverse || !SET.test(String(card.id || ""))) return false;
  if (card.foilAs || card.pattern || card.reverseMap) return false;
  if (card.reverseKind && card.reverseKind !== "cosmos") return false;
  const classes = base?.classes || "";
  return classes === "rev-mirror" || classes === "";
}

export function famExtras(card, url, base) {
  if (!claims(card, base)) return null;
  return { classes: "fam-me-reverse", style: "", cure: false };
}
