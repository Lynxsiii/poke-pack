/**
 * Holo family wotc-reverse: the reverse faces of Base Set to Neo Destiny (reverse round, 2026-11-28).
 *
 * Scope: every reverse face of base1-base5, gym1-gym2 and neo1-neo4 (1,029 faces). Wizards printed no reverse before
 * Legendary Collection (wotc-pack-structure.md); the game data deals these faces, so they wear the plain mirror of the
 * first real reverses: the whole face inside the yellow border except the picture, no pattern. The era left them on
 * sv-reverse.css's colour-dodged mirror under the Scarlet & Violet art window (`rev-mirror era-wotc wotc-rev`): the matte
 * box sat 30 px off the print, a foil strip ran along the picture's bottom and right edges, and the text box blew to
 * flat white (2026-11-28 reverse review: Base to Rocket 14 of 15 bad, Neo 12 of 12).
 *
 * What it adds (css/holo/fam/wotc-reverse.css, generated by scripts/fam/mirror-reverse/make_sheets.py):
 *   fam-wotc-reverse   every face it claims.
 *   --wr-mask          where the face is foil: assets/foil/fam/wotc-reverse/<pokemon|trainer|energy>-v1.webp
 *                      (scripts/fam/wotc-reverse/make_masks.py: the face inside the border less the era's art window,
 *                      grown so the gold bevel stays matte on every scan).
 *
 * `base` is foilExtras()'s own result for the face. Never import js/foil-maps.js from here (it waits on this module).
 */
import { isWotc, wotcLayout } from "../wotc-foil.js?v=6";

const SETS = /^(base[1-5]|gym[12]|neo[1-4])-/;

/** Whether a card face is this family's: a plain `wotc-rev` reverse of Base Set to Neo Destiny. */
export function claims(card, base) {
  if (!card?.reverse || !isWotc(card) || !SETS.test(String(card.id || ""))) return false;
  return /(^| )wotc-rev( |$)/.test(base?.classes || "") && !/wotc-rev-/.test(base?.classes || "");
}

export function famExtras(card, url, base) {
  if (!claims(card, base)) return null;
  return {
    classes: "fam-wotc-reverse",
    style: `--wr-mask:url('${url(`assets/foil/fam/wotc-reverse/${wotcLayout(card)}-v1.webp`)}')`,
    cure: false,
  };
}
