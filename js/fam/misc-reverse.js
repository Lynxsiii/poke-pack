/**
 * Holo family misc-reverse: the reverse faces no era finish covered (reverse round, 2026-11-28).
 *
 * Scope (48 faces): Trick or Trade 2023 and 2024 (tot23, tot24), VMAX Climax's basic Energy (js8b-286 to 293) and the
 * Sun & Moon Special Energy (sm1-sm12, sm35, jsm12a). reverseFinish() returns "" for all of them, so they fell to
 * rarities.css's generic reverse: the cosmos tile colour-dodged at 180 px, which reads as white cracked blotches over
 * the text box and frame, cut off at a hard edge by the Scarlet & Violet window mask (2026-11-28 reverse review: 11 of
 * 11 bad). They take the plain mirror: a real Japanese high-class basic Energy is a mirror edge to edge, a Special
 * Energy reverse is foil round its picture.
 *
 * What it adds (css/holo/fam/misc-reverse.css, generated by scripts/fam/mirror-reverse/make_sheets.py):
 *   fam-misc-reverse   every face it claims; the mask is the card less the layout's art window (the site's --win-*).
 *   mx-basic           a basic Energy: foil over the whole face inside the border.
 *
 * `base` is foilExtras()'s own result for the face. Never import js/foil-maps.js from here (it waits on this module).
 */
const SET = /^(tot2[34]|js8b|j?sm\d+[a-z]?)-/;

/** Whether a card face is this family's: a reverse of those sets that the era gave no finish. */
export function claims(card, base) {
  if (!card?.reverse || !SET.test(String(card.id || ""))) return false;
  if (card.foilAs || card.pattern || card.reverseMap) return false;
  if (card.reverseKind && card.reverseKind !== "cosmos") return false;
  return !(base?.classes || "");
}

export function famExtras(card, url, base) {
  if (!claims(card, base)) return null;
  const energy = card.supertype === "Energy" || card.energy;
  const basic = energy && !(card.subtypes || []).includes("Special");
  return { classes: `fam-misc-reverse${basic ? " mx-basic" : ""}`, style: "", cure: false };
}
