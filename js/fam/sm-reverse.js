/**
 * Holo family sm-reverse: the Sun & Moon reverses of Fighting and Colorless Pokémon (reverse round, 2026-11-28).
 *
 * Scope: every Sun & Moon reverse face (sm1-sm12, the side sets, Tag All Stars) the era marks `rev-sm rev-fighting` or
 * `rev-sm rev-colorless` (375 faces; no Energy). The era's recipe (css/holo/sm.css: the type tile times a spectrum
 * band, colour-dodged onto the print) reads well on the saturated bodies, which stay on it. On Fighting's orange it
 * glared bright yellow behind the text and washed the flavour text; on Colorless's near-white it blew the text box to
 * flat white (2026-11-28 reverse review: all 6 Fighting and 2 of 3 Colorless samples bad, every other type good).
 *
 * What it adds (css/holo/fam/sm-reverse.css, generated by scripts/fam/mirror-reverse/make_sheets.py):
 *   fam-sm-reverse   every face it claims: the mirror recipe (a pastel pool round the lamp, multiplied; a white core)
 *                    with the era's own type tile (--rev-pattern, already on the face) as the sheet's pattern.
 *
 * `base` is foilExtras()'s own result for the face. Never import js/foil-maps.js from here (it waits on this module).
 */
import { isSm } from "../sm-foil.js?v=9";

/** Whether a card face is this family's. */
export function claims(card, base) {
  if (!card?.reverse || !isSm(card)) return false;
  const classes = ` ${base?.classes || ""} `;
  if (!classes.includes(" rev-sm ") || classes.includes(" rev-energy ")) return false;
  return classes.includes(" rev-fighting ") || classes.includes(" rev-colorless ");
}

export function famExtras(card, url, base) {
  if (!claims(card, base)) return null;
  return { classes: "fam-sm-reverse", style: "", cure: false };
}
