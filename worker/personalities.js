export function affinity(persona, card) {
  const name = String(card.name || "").toLowerCase();
  if (name.includes(String(persona.favorite || "\0").toLowerCase())) return 3;
  if ((persona.family || []).some(n => name.includes(n.toLowerCase()))) return 2;
  return (card.types || []).includes(persona.type) ? 1 : 0;
}
